"""
exp_h14_qidmo_cxm.py - hypothesis H14 (the swap move, CXM, transferred unchanged to QI-DMO); pre-registered in
research_plan_v5.md §31 before this script was run. p_x = 1 and c = 0.25 are fixed a priori (no tuning for QI-DMO).

  python experiments/exp_h14_qidmo_cxm.py test      # 8 TEST families x FRESH instance seeds 701-710 x run seeds 0-1: DMO, QI-DMO, QI-DMO+CXM
  python experiments/exp_h14_qidmo_cxm.py scale     # descriptive (P3): QI-DMO+CXM on the scaling problems of §29 (500-5000 tasks, 10 runs)
  python experiments/exp_h14_qidmo_cxm.py analyze   # statistics -> results/h14_analysis.md

Outputs are new, write-once files: results/h14_test/, results/h14_scale/, results/h14_analysis.md.
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))   # the qi_* modules
import numpy as np
import pandas as pd
from scipy import stats
from qi_experiment import spec, make_jobs, run_experiment, load_experiment, paired_table, holm, TEST_FAMILIES, family_name

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.environ.get("QI_RESULTS_DIR", os.path.join(os.path.dirname(HERE), "results"))
BUDGET, P = 20000, 30
H14_INST_SEEDS = list(range(701, 711))              # never used before (static: H5 101-110, H7 201-210)
ALGOS = {"DMO": spec("run_dmo"),
         "QI-DMO": spec("run_qidmo", decoherence_c=0.25),
         "QI-DMO+CXM": spec("run_qidmo", decoherence_c=0.25, exchange=1.0)}
SCALE_SIZES = [500, 1000, 1500, 2000, 5000]
SCALE_FAMILIES = [(n, 50, "uniform", "high") for n in SCALE_SIZES]          # the problems of the scaling study (§29)


def stage_test():
    jobs = make_jobs("h14_test", ALGOS, TEST_FAMILIES, H14_INST_SEEDS, [0, 1], BUDGET, P)
    run_experiment("h14_test", jobs, config={"budget": BUDGET, "P": P, "algos": ALGOS, "inst_seeds": H14_INST_SEEDS,
                                             "families": [family_name(f) for f in TEST_FAMILIES]})


def stage_scale():
    jobs = make_jobs("h14_scale", {"QI-DMO+CXM": ALGOS["QI-DMO+CXM"]}, SCALE_FAMILIES, [1], list(range(10)), BUDGET, P)
    run_experiment("h14_scale", jobs, config={"budget": BUDGET, "P": P, "sizes": SCALE_SIZES, "inst_seeds": [1],
                                              "run_seeds": list(range(10)), "compare_with": "results/scale_tasks QI-DMO"})


def analysis_text():
    test = load_experiment("h14_test")
    algos = list(ALGOS)
    out = ["# H14 analysis — the swap move (CXM) in QI-DMO\n",
           "Generated by `python experiments/exp_h14_qidmo_cxm.py analyze` from `results/h14_test/records.csv` (fresh instance seeds "
           "701-710, 2 run seeds, 20 000 evaluations, P = 30) and `results/h14_scale/records.csv`. p_x = 1 and c = 0.25 fixed "
           "a priori (research_plan_v5.md §31). gap2 = gap to the preemptive lower bound, in %.\n",
           "## Mean gap2 (%) per family\n"]
    pv = test.pivot_table(index="family", columns="algo", values="gap2", aggfunc="mean")[algos] * 100
    out.append(pv.round(3).reset_index().to_markdown(index=False, floatfmt=".3f"))
    ms = test.pivot_table(index="family", columns="algo", values="makespan", aggfunc="mean")[algos]
    out.append("\n## Mean makespan (s) per family\n")
    out.append(ms.round(2).reset_index().to_markdown(index=False, floatfmt=".2f"))

    cols = ["family", "pairs", "mean A", "mean B", "diff A-B", "CI95 lo", "CI95 hi", "wins A", "ties", "wins B", "p", "p_holm", "r_rb", "A12"]
    out.append("\n## Paired comparisons (unit = instance, mean of 2 run seeds; diff in gap2 pp; Holm across 8 families; "
               "ALL = pooled over the 80 instances)\n")
    tables = {}
    for a, b, label in [("QI-DMO+CXM", "QI-DMO", "P1/P2 (primary): QI-DMO+CXM vs QI-DMO"),
                        ("QI-DMO", "DMO", "reference: QI-DMO vs the original DMO")]:
        t = paired_table(test, a, b, metric="gap2"); tables[(a, b)] = t
        out.append(f"### {label}: A = {a}, B = {b}\n"); out.append(t[cols].to_markdown(index=False, floatfmt=".4f") + "\n")

    t = tables[("QI-DMO+CXM", "QI-DMO")]
    pooled, fams = t[t.family == "ALL"].iloc[0], t[t.family != "ALL"]
    p1 = bool(pooled["diff A-B"] < 0 and pooled["CI95 hi"] < 0 and pooled["p"] < 0.05)
    worse = fams[(fams["diff A-B"] > 0) & (fams["p_holm"] < 0.05)]
    p2 = len(worse) == 0
    out.append("## Pre-registered criteria (computed mechanically)\n")
    out.append(f"* **P1:** mean diff {pooled['diff A-B']:.4f} pp, CI95 [{pooled['CI95 lo']:.4f}, {pooled['CI95 hi']:.4f}], "
               f"Wilcoxon p = {pooled['p']:.3g}, QI-DMO+CXM better on {int(pooled['wins A'])} of {int(pooled['pairs'])} "
               f"instances -> **{'holds' if p1 else 'fails'}**.")
    out.append(f"* **P2:** families with a Holm-significant deterioration: {len(worse)} "
               f"({', '.join(worse.family) if len(worse) else 'none'}) -> **{'holds' if p2 else 'fails'}**.")
    verdict = "RETAIN" if (p1 and p2) else ("RETAIN WITH BOUNDARY" if p1 else "REJECT")
    out.append(f"* **Verdict by §31:** **{verdict}**.\n")

    mech = ["x_success", "x_frac", "end_impr_swap", "end_impr_reloc", "last_gb_impr_frac", "improving", "dup_global_frac",
            "move_size", "purity_end", "runtime_s"]
    out.append("## Mechanism diagnostics (means over runs)\n")
    out.append(test.groupby("algo")[mech].mean().reindex(algos).round(4).reset_index().to_markdown(index=False, floatfmt=".4f"))

    # P3 (descriptive): scaling problems; QI-DMO = the committed scale_tasks records (same problems, same run seeds)
    sc = load_experiment("h14_scale")
    base = load_experiment("scale_tasks")
    base = base[base.algo.isin(["DMO", "QI-DMO"])]
    both = pd.concat([base, sc], ignore_index=True)
    rows, ps = [], []
    for n in SCALE_SIZES:
        xa = sc[sc.n == n].makespan.values; xb = base[(base.n == n) & (base.algo == "QI-DMO")].makespan.values
        xd = base[(base.n == n) & (base.algo == "DMO")].makespan.values
        p = stats.mannwhitneyu(xa, xb, alternative="two-sided").pvalue; ps.append(p)
        rows.append({"tasks": n, "DMO mean (s)": xd.mean(), "QI-DMO mean (s)": xb.mean(), "QI-DMO+CXM mean (s)": xa.mean(),
                     "QI-DMO+CXM sd (s)": xa.std(ddof=1), "diff CXM - QI-DMO (s)": xa.mean() - xb.mean(),
                     "every CXM run better": bool(xa.max() < xb.min()), "p (Mann-Whitney)": p,
                     "runtime QI-DMO (s)": base[(base.n == n) & (base.algo == "QI-DMO")].runtime_s.mean(),
                     "runtime QI-DMO+CXM (s)": sc[sc.n == n].runtime_s.mean()})
    for r, ph in zip(rows, holm(ps)): r["p_holm"] = ph
    out.append("\n## P3 (descriptive): scaling problems, 50 VMs, 10 runs (QI-DMO and DMO from results/scale_tasks)\n")
    out.append(pd.DataFrame(rows).to_markdown(index=False, floatfmt=".4f"))
    gap = both.groupby(["n", "algo"]).gap.mean().unstack("algo")[["DMO", "QI-DMO", "QI-DMO+CXM"]] * 100
    out.append("\nMean gap to the lower bound (%):\n")
    out.append(gap.round(3).reset_index().to_markdown(index=False, floatfmt=".3f"))
    return "\n".join(out) + "\n"


def stage_analyze():
    path = os.path.join(RES, "h14_analysis.md")
    if os.path.exists(path):
        raise RuntimeError(f"{path} exists (write-once)")
    txt = analysis_text(); open(path, "w").write(txt); print(txt)


if __name__ == "__main__":
    {"test": stage_test, "scale": stage_scale, "analyze": stage_analyze}[sys.argv[1]]()
