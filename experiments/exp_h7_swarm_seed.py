"""
exp_h7_swarm_seed.py - hypothesis H7 (is the register swarm needed once CXM exists? does Max-Min seeding remove the
big-task plateau failure?); design pre-registered in research_plan_v5.md §12 before this script was run.

  python experiments/exp_h7_swarm_seed.py tune      # development set: tune the (1+1)-EA control's (c, p_x) with the same effort as H5
  python experiments/exp_h7_swarm_seed.py test      # FRESH held-out set: the 8 H5 families x 10 NEW instance seeds (201-210) x 2 seeds
  python experiments/exp_h7_swarm_seed.py analyze   # statistics -> results/h7_analysis.md

Outputs are new, write-once files: results/h7_tune/, results/h7_selection.json, results/h7_test/, results/h7_analysis.md.
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))   # the qi_* modules
import json, os, sys
import numpy as np
import pandas as pd
from qi_experiment import (spec, make_jobs, run_experiment, load_experiment, paired_table, mean_ranks,
                           TUNE_FAMILIES, TUNE_INST_SEEDS, TEST_FAMILIES, family_name)

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.environ.get("QI_RESULTS_DIR", os.path.join(os.path.dirname(HERE), "results"))
BUDGET, P = 20000, 30
TEST2_INST_SEEDS = list(range(201, 211))          # never used before H7 (H5 used 101-110, the pilots 1)
C_GRID, PX_GRID = [0.25, 1.0, 2.0], [0.5, 1.0]
SEL_PATH = os.path.join(RES, "h7_selection.json")


def tune_algos():
    return {f"(1+1)-EA+CXM c={c} px={px}": spec("run_one_plus_one", decoherence_c=c, exchange=px) for c in C_GRID for px in PX_GRID}


def test_algos(c1, px1):
    ea = dict(decoherence_c=c1, exchange=px1)
    return {"Max-Min": spec("max_min"),
            "QI-MRFO+CXM": spec("run_qimrfo", decoherence_c=1.0, exchange=1.0),
            "QI-MRFO+CXM+seed": spec("run_qimrfo", decoherence_c=1.0, exchange=1.0, seed_heuristic="max_min"),
            "P-MRFO+CXM": spec("run_qimrfo", decoherence_c=1.0, exchange=1.0, mode="linear"),
            "P-MRFO+CXM+seed": spec("run_qimrfo", decoherence_c=1.0, exchange=1.0, mode="linear", seed_heuristic="max_min"),
            "(1+1)-EA+CXM": spec("run_one_plus_one", **ea),
            "(1+1)-EA+CXM+seed": spec("run_one_plus_one", **ea, seed_heuristic="max_min"),
            "GA+CXM+seed": spec("run_ga", exchange=1.0, seed_heuristic="max_min")}


def stage_tune():
    jobs = make_jobs("h7_tune", tune_algos(), TUNE_FAMILIES, TUNE_INST_SEEDS, list(range(10)), BUDGET, P)
    df = run_experiment("h7_tune", jobs, config={"stage": "tune", "c_grid": C_GRID, "px_grid": PX_GRID, "budget": BUDGET,
                                                "note": "development set; selection bias applies"})
    r = mean_ranks(df, list(tune_algos()), metric="gap2", block=("family", "inst_seed", "run_seed"))
    gap = df.groupby("algo").gap2.mean()
    # pre-registered selection: best mean rank; ties broken by the lower mean development gap2 (plan §9 rule)
    best = sorted(r.index, key=lambda a: (round(r[a], 9), gap[a]))[0]
    c = float(best.split("c=")[1].split()[0]); px = float(best.split("px=")[1])
    sel = {"(1+1)-EA+CXM": {"c": c, "px": px, "mean_ranks": r.round(4).to_dict(), "mean_gap2": gap.round(6).to_dict()}}
    if os.path.exists(SEL_PATH):
        raise RuntimeError(f"{SEL_PATH} exists (write-once)")
    json.dump(sel, open(SEL_PATH, "w"), indent=1); print(json.dumps(sel, indent=1))


def stage_test():
    sel = json.load(open(SEL_PATH))["(1+1)-EA+CXM"]
    jobs = make_jobs("h7_test", test_algos(sel["c"], sel["px"]), TEST_FAMILIES, TEST2_INST_SEEDS, [0, 1], BUDGET, P)
    run_experiment("h7_test", jobs, config={"stage": "test", "one_plus_one": sel, "budget": BUDGET, "P": P,
                                            "families": [family_name(f) for f in TEST_FAMILIES], "inst_seeds": TEST2_INST_SEEDS})


def analysis_text():
    test = load_experiment("h7_test"); sel = json.load(open(SEL_PATH))["(1+1)-EA+CXM"]
    algos = ["Max-Min", "GA+CXM+seed", "(1+1)-EA+CXM", "(1+1)-EA+CXM+seed", "P-MRFO+CXM", "P-MRFO+CXM+seed", "QI-MRFO+CXM", "QI-MRFO+CXM+seed"]
    out = ["# H7 analysis — swarm vs (1+1)-EA with identical moves; Max-Min seeding\n",
           f"Generated by `python experiments/exp_h7_swarm_seed.py analyze` from `results/h7_test/records.csv` (fresh instance seeds 201-210). "
           f"(1+1)-EA+CXM uses c = {sel['c']}, p_x = {sel['px']} chosen on the development set (`results/h7_tune/`). gap2 in %.\n",
           "## Mean gap to the preemptive lower bound (%)\n"]
    pv = test.pivot_table(index="family", columns="algo", values="gap2", aggfunc="mean")[algos] * 100
    out.append(pv.round(3).reset_index().to_markdown(index=False, floatfmt=".3f"))
    rk = mean_ranks(test, algos, metric="makespan", block=("family", "inst_seed", "run_seed"))
    out.append("\nMean rank over all 160 (instance, seed) blocks (1 = best): " + ", ".join(f"{a} {v:.2f}" for a, v in rk.items()) + "\n")
    comps = [("QI-MRFO+CXM", "(1+1)-EA+CXM", "H7a primary: register swarm vs (1+1)-EA with identical moves (unseeded)"),
             ("P-MRFO+CXM", "(1+1)-EA+CXM", "H7a (classical twin): swarm vs (1+1)-EA (unseeded)"),
             ("QI-MRFO+CXM+seed", "QI-MRFO+CXM", "H7b: effect of Max-Min seeding on QI-MRFO+CXM"),
             ("QI-MRFO+CXM+seed", "(1+1)-EA+CXM+seed", "H7c: seeded swarm vs Max-Min + stochastic CXM local search"),
             ("QI-MRFO+CXM+seed", "Max-Min", "seeded swarm vs Max-Min"),
             ("QI-MRFO+CXM+seed", "GA+CXM+seed", "seeded swarm vs seeded GA (both CXM)"),
             ("P-MRFO+CXM+seed", "QI-MRFO+CXM+seed", "linear twin vs Born rule, both seeded (replication of H5 P4)"),
             ("QI-MRFO+CXM", "Max-Min", "replication of H5 on fresh instances: QI-MRFO+CXM vs Max-Min")]
    cols = ["family", "pairs", "mean A", "mean B", "diff A-B", "CI95 lo", "CI95 hi", "wins A", "ties", "wins B", "p", "p_holm", "r_rb", "A12"]
    out.append("## Paired comparisons (unit = instance, mean of 2 run seeds; diff in gap2 pp; Holm across 8 families; ALL = pooled over 80 instances)\n")
    for a, b, label in comps:
        t = paired_table(test, a, b, metric="gap2")
        out.append(f"### {label}: A = {a}, B = {b}\n"); out.append(t[cols].to_markdown(index=False, floatfmt=".4f") + "\n")
    out.append("## Mechanism diagnostics (means over runs)\n")
    mech = ["end_impr_swap", "end_impr_reloc", "last_gb_impr_frac", "late_improving_frac", "improving", "dup_global_frac", "x_success",
            "move_size", "div_end", "purity_end", "runtime_s"]
    out.append(test[test.algo.isin(algos[1:])].groupby("algo")[mech].mean().round(4).reset_index().to_markdown(index=False, floatfmt=".4f"))
    cps = ["bsf_005", "bsf_010", "bsf_025", "bsf_050", "bsf_075", "bsf_100"]
    conv = test[test.algo.isin(algos[1:])].copy()
    for c in cps: conv[c] = (conv[c] - conv.lb2) / conv.lb2 * 100
    out.append("\n## Convergence: mean gap2 (%) at fractions of the budget (pooled)\n")
    out.append(conv.groupby("algo")[cps].mean().round(3).reset_index().to_markdown(index=False, floatfmt=".3f"))
    return "\n".join(out) + "\n"


def stage_analyze():
    path = os.path.join(RES, "h7_analysis.md")
    if os.path.exists(path):
        raise RuntimeError(f"{path} exists (write-once)")
    txt = analysis_text(); open(path, "w").write(txt); print(txt)


if __name__ == "__main__":
    {"tune": stage_tune, "test": stage_test, "analyze": stage_analyze}[sys.argv[1]]()
