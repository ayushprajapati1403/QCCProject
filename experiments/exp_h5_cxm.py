"""
exp_h5_cxm.py - hypothesis H5 (critical exchange measurement, CXM); design pre-registered in research_plan_v5.md §7-8.

  python experiments/exp_h5_cxm.py tune      # development set (4 pilot instances, 10 seeds): choose p_x for QI-MRFO+CXM and GA+CXM
  python experiments/exp_h5_cxm.py test      # held-out set (8 families x 10 new instances x 2 seeds) with the chosen p_x frozen
  python experiments/exp_h5_cxm.py analyze   # statistics + mechanism tables -> results/h5_analysis.md

Outputs are new, write-once files: results/h5_tune/, results/h5_selection.json, results/h5_test/, results/h5_analysis.md.
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))   # the qi_* modules
import json, os, sys
import numpy as np
import pandas as pd
from qi_experiment import (spec, make_jobs, run_experiment, load_experiment, paired_table, mean_ranks,
                           TUNE_FAMILIES, TUNE_INST_SEEDS, TEST_FAMILIES, TEST_INST_SEEDS, family_name)

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.environ.get("QI_RESULTS_DIR", os.path.join(os.path.dirname(HERE), "results"))
BUDGET, P = 20000, 30
PX_GRID = [0.1, 0.25, 0.5, 1.0]
SEL_PATH = os.path.join(RES, "h5_selection.json")


def tune_algos():
    a = {"QI-MRFO": spec("run_qimrfo", decoherence_c=1.0), "GA": spec("run_ga")}
    for px in PX_GRID:
        a[f"QI-MRFO+CXM px={px}"] = spec("run_qimrfo", decoherence_c=1.0, exchange=px)
        a[f"GA+CXM px={px}"] = spec("run_ga", exchange=px)
    return a


def test_algos(px_q, px_g):
    return {"Max-Min": spec("max_min"), "Min-Min": spec("min_min"), "MRFO": spec("run_mrfo"),
            "GA": spec("run_ga"), "GA+CXM": spec("run_ga", exchange=px_g),
            "QI-MRFO": spec("run_qimrfo", decoherence_c=1.0), "QI-MRFO+CXM": spec("run_qimrfo", decoherence_c=1.0, exchange=px_q),
            "QI-MRFO+CXM px=0.5 (sensitivity)": spec("run_qimrfo", decoherence_c=1.0, exchange=0.5),   # amendment §9 of the plan
            "P-MRFO": spec("run_qimrfo", decoherence_c=1.0, mode="linear"),
            "P-MRFO+CXM": spec("run_qimrfo", decoherence_c=1.0, mode="linear", exchange=px_q)}


def stage_tune():
    jobs = make_jobs("h5_tune", tune_algos(), TUNE_FAMILIES, TUNE_INST_SEEDS, list(range(10)), BUDGET, P)
    df = run_experiment("h5_tune", jobs, config={"stage": "tune", "px_grid": PX_GRID, "budget": BUDGET, "P": P,
                                                "note": "development set = pilot instances; selection bias applies to any number reported from it"})
    sel = {}
    for host in ("QI-MRFO", "GA"):
        cands = [f"{host}+CXM px={px}" for px in PX_GRID]
        r = mean_ranks(df, cands, metric="gap2", block=("family", "inst_seed", "run_seed"))
        sel[host] = {"px": float(r.index[0].split("px=")[1]), "mean_ranks": r.round(3).to_dict()}
    if os.path.exists(SEL_PATH):
        raise RuntimeError(f"{SEL_PATH} exists (write-once)")
    json.dump(sel, open(SEL_PATH, "w"), indent=1)
    print(json.dumps(sel, indent=1))


def stage_test():
    sel = json.load(open(SEL_PATH))
    px_q, px_g = sel["QI-MRFO"]["px"], sel["GA"]["px"]
    jobs = make_jobs("h5_test", test_algos(px_q, px_g), TEST_FAMILIES, TEST_INST_SEEDS, [0, 1], BUDGET, P)
    run_experiment("h5_test", jobs, config={"stage": "test", "px_qimrfo": px_q, "px_ga": px_g, "budget": BUDGET, "P": P,
                                            "families": [family_name(f) for f in TEST_FAMILIES], "inst_seeds": TEST_INST_SEEDS})


def fmt(t, cols=None, digits=3):
    t = t if cols is None else t[cols]
    return t.to_markdown(index=False, floatfmt=f".{digits}f") if hasattr(t, "to_markdown") else t.to_string(index=False)


def analysis_text():
    out = []
    tune, test = load_experiment("h5_tune"), load_experiment("h5_test")
    sel = json.load(open(SEL_PATH))
    out.append("# H5 analysis — critical exchange measurement (CXM)\n")
    out.append("Generated by `python experiments/exp_h5_cxm.py analyze` from `results/h5_tune/records.csv` and `results/h5_test/records.csv`. "
               "Gaps are relative to the preemptive lower bound (`gap2`, %), unless stated.\n")
    # ---------------- development set
    out.append("## 1. Development (TUNE) set — pilot instances, 10 seeds. SELECTION BIAS: p_x was chosen on these numbers\n")
    pv = tune.pivot_table(index="algo", columns="family", values="gap2", aggfunc="mean") * 100
    pv["mean"] = pv.mean(1)
    out.append(pv.round(3).reset_index().to_markdown(index=False, floatfmt=".3f"))
    out.append(f"\nSelected: QI-MRFO+CXM p_x = {sel['QI-MRFO']['px']}, GA+CXM p_x = {sel['GA']['px']} (best mean rank; ranks: "
               f"{sel['QI-MRFO']['mean_ranks']} / {sel['GA']['mean_ranks']})\n")
    # ---------------- held-out set
    algos = ["Max-Min", "Min-Min", "MRFO", "GA", "GA+CXM", "P-MRFO", "P-MRFO+CXM", "QI-MRFO", "QI-MRFO+CXM"]
    out.append("## 2. Held-out (TEST) set — 8 families x 10 instances x 2 run seeds, 20 000 evaluations\n")
    pv = test.pivot_table(index="family", columns="algo", values="gap2", aggfunc="mean")[algos] * 100
    out.append("Mean gap to the preemptive lower bound (%):\n")
    out.append(pv.round(3).reset_index().to_markdown(index=False, floatfmt=".3f"))
    rk = mean_ranks(test, algos, metric="makespan", block=("family", "inst_seed", "run_seed"))
    out.append("\nMean rank over all 160 (instance, seed) blocks (1 = best): " + ", ".join(f"{a} {v:.2f}" for a, v in rk.items()) + "\n")
    # ---------------- primary + secondary tests
    comps = [("QI-MRFO+CXM", "QI-MRFO", "P1 primary: effect of CXM on QI-MRFO"),
             ("P-MRFO+CXM", "QI-MRFO+CXM", "P4: linear twin vs Born rule under CXM"),
             ("GA+CXM", "GA", "P5: effect of CXM on the GA"),
             ("QI-MRFO+CXM", "GA+CXM", "register swarm vs GA, both with CXM"),
             ("QI-MRFO+CXM", "GA", "vs unchanged GA"),
             ("QI-MRFO+CXM", "Max-Min", "vs Max-Min"),
             ("QI-MRFO", "Max-Min", "reference: unchanged QI-MRFO vs Max-Min"),
             ("QI-MRFO", "P-MRFO", "reference: Born vs linear without CXM"),
             ("QI-MRFO+CXM px=0.5 (sensitivity)", "QI-MRFO", "sensitivity arm (plan §9): p_x = 0.5 instead of 1.0")]
    out.append("## 3. Paired comparisons (unit = instance, mean of 2 run seeds; diff in gap2 percentage points; Holm across the 8 families; ALL = pooled test over 80 instances)\n")
    cols = ["family", "pairs", "mean A", "mean B", "diff A-B", "CI95 lo", "CI95 hi", "wins A", "ties", "wins B", "p", "p_holm", "r_rb", "A12"]
    tables = {}
    for a, b, label in comps:
        t = paired_table(test, a, b, metric="gap2"); tables[(a, b)] = t
        out.append(f"### {label}: A = {a}, B = {b}\n")
        out.append(t[cols].to_markdown(index=False, floatfmt=".4f") + "\n")
    # ---------------- mechanism diagnostics
    out.append("## 4. Mechanism diagnostics (means over the TEST runs)\n")
    mech = ["end_impr_swap", "end_impr_reloc", "last_gb_impr_frac", "late_improving_frac", "improving", "dup_global_frac", "wasted",
            "touch_crit_frac", "x_frac", "x_success", "move_size", "div_end", "purity_end", "runtime_s"]
    mt = test[test.algo.isin(["GA", "GA+CXM", "P-MRFO", "P-MRFO+CXM", "QI-MRFO", "QI-MRFO+CXM", "Max-Min"])].groupby("algo")[mech].mean()
    out.append(mt.round(4).reset_index().to_markdown(index=False, floatfmt=".4f"))
    out.append("\nPer family (QI-MRFO -> QI-MRFO+CXM): improving swaps left at the end point, last global-best improvement (fraction of budget), late-half improving fraction\n")
    fam = test[test.algo.isin(["QI-MRFO", "QI-MRFO+CXM"])].pivot_table(index="family", columns="algo",
                                                                     values=["end_impr_swap", "last_gb_impr_frac", "late_improving_frac"], aggfunc="mean")
    out.append(fam.round(4).to_markdown(floatfmt=".4f"))
    # ---------------- P2: dose-response across families
    base_sw = test[test.algo == "QI-MRFO"].groupby("family").end_impr_swap.mean()
    eff = tables[("QI-MRFO+CXM", "QI-MRFO")].set_index("family")["diff A-B"].drop("ALL")
    from scipy.stats import spearmanr
    rho, p = spearmanr(base_sw.reindex(eff.index), eff)
    out.append(f"\n**P2 (dose-response across families):** Spearman correlation between the unchanged QI-MRFO's improving swaps at "
               f"its end point and the CXM effect (diff in pp, negative = CXM better) over the 8 families: rho = {rho:.3f} (p = {p:.3f}). "
               "The prediction is a NEGATIVE rho: more unused swaps, larger gain.\n")
    out.append(pd.DataFrame({"baseline improving swaps at end": base_sw.reindex(eff.index), "CXM effect (pp)": eff}).round(4).reset_index().to_markdown(index=False, floatfmt=".4f"))
    # ---------------- convergence checkpoints
    out.append("\n## 5. Convergence: mean gap2 (%) at fractions of the budget (all TEST families pooled)\n")
    cps = ["bsf_005", "bsf_010", "bsf_025", "bsf_050", "bsf_075", "bsf_100"]
    conv = test[test.algo.isin(["GA", "GA+CXM", "P-MRFO", "P-MRFO+CXM", "QI-MRFO", "QI-MRFO+CXM"])].copy()
    for c in cps: conv[c] = (conv[c] - conv.lb2) / conv.lb2 * 100
    out.append(conv.groupby("algo")[cps].mean().round(3).reset_index().to_markdown(index=False, floatfmt=".3f"))
    return "\n".join(out) + "\n"


def stage_analyze():
    path = os.path.join(RES, "h5_analysis.md")
    if os.path.exists(path):
        raise RuntimeError(f"{path} exists (write-once)")
    txt = analysis_text(); open(path, "w").write(txt); print(txt)


def stage_posthoc():
    """EXPLORATORY (not pre-registered), written after reading results/h5_analysis.md: P2 re-expressed as the RELATIVE gap
    reduction (the pre-registered absolute pp effect is capped by each family's baseline gap), and the structure of the
    one family where QI-MRFO+CXM loses to Max-Min."""
    from scipy.stats import spearmanr
    from qi_core import make_instance, Objective, max_min
    path = os.path.join(RES, "h5_posthoc.md")
    if os.path.exists(path):
        raise RuntimeError(f"{path} exists (write-once)")
    test = load_experiment("h5_test")
    w = test[test.algo.isin(["QI-MRFO", "QI-MRFO+CXM"])].groupby(["family", "inst_seed", "algo"])[["gap2", "end_impr_swap"]].mean().unstack("algo")
    rel = 1 - w["gap2"]["QI-MRFO+CXM"] / w["gap2"]["QI-MRFO"]
    sw = w["end_impr_swap"]["QI-MRFO"]
    fam = pd.DataFrame({"relative gap reduction": rel.groupby(level=0).mean(), "baseline unused improving swaps": sw.groupby(level=0).mean()})
    r_f, p_f = spearmanr(fam.iloc[:, 1], fam.iloc[:, 0]); r_i, p_i = spearmanr(sw, rel)
    out = ["# H5 post hoc analysis (EXPLORATORY — not pre-registered)\n",
           "Written after reading `results/h5_analysis.md`. Nothing here is a confirmatory test.\n",
           "## P2 re-expressed as the relative gap reduction 1 - gap2(QI-MRFO+CXM) / gap2(QI-MRFO)\n",
           fam.round(3).reset_index().to_markdown(index=False, floatfmt=".3f"),
           f"\nSpearman (baseline unused swaps vs relative reduction): families rho = {r_f:.3f} (p = {p_f:.3f}); "
           f"instances rho = {r_i:.3f} (p = {p_i:.4f}, n = {len(rel)}).\n",
           "## Why QI-MRFO+CXM loses to Max-Min on 'n100 m20 lognormal low'\n",
           "| inst_seed | LB2 | L_max / S_max | total work / total speed | Max-Min makespan | QI-MRFO+CXM (mean of 2 seeds) |",
           "|---|---|---|---|---|---|"]
    q = test[(test.algo == "QI-MRFO+CXM") & (test.family == "n100 m20 lognormal low")].groupby("inst_seed").makespan.mean()
    for s in TEST_INST_SEEDS:
        inst = make_instance(100, 20, seed=s, task_dist="lognormal", hetero="low")
        out.append(f"| {s} | {inst.lower_bound_pmtn():.3f} | {inst.task_len.max() / inst.vm_mips.max():.3f} | "
                   f"{inst.task_len.sum() / inst.vm_mips.sum():.3f} | {Objective(inst)._raw(max_min(inst))[0]:.3f} | {q.loc[s]:.3f} |")
    out.append("\nOn every instance the bound is set by the largest task alone on the fastest VM, and Max-Min attains it, so it is "
               "provably optimal. Reaching that schedule by local moves requires emptying the fastest VM first; every such "
               "move is makespan-neutral and is rejected by strict acceptance (a plateau, like the V4 identical-task case).\n")
    txt = "\n".join(out) + "\n"; open(path, "w").write(txt); print(txt)


if __name__ == "__main__":
    {"tune": stage_tune, "test": stage_test, "analyze": stage_analyze, "posthoc": stage_posthoc}[sys.argv[1]]()
