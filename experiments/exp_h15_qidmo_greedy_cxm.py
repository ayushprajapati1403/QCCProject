"""
exp_h15_qidmo_greedy_cxm.py - hypothesis H15 (the swap move only in QI-DMO's greedy phases, p_x chosen on the
development set); pre-registered in research_plan_v5.md §33 before this script was run. Protocol as H5: tune on the
pilot instances, freeze the choice, test once on fresh instances.

  python experiments/exp_h15_qidmo_greedy_cxm.py tune      # 4 pilot instances x 10 run seeds: QI-DMO and 8 CXM configurations
  python experiments/exp_h15_qidmo_greedy_cxm.py test      # 8 TEST families x FRESH instance seeds 801-810 x run seeds 0-1
  python experiments/exp_h15_qidmo_greedy_cxm.py scale     # descriptive (P3): the selected configuration on the scaling problems
  python experiments/exp_h15_qidmo_greedy_cxm.py analyze   # statistics -> results/h15_analysis.md

Outputs are new, write-once files: results/h15_tune/, results/h15_selection.json, results/h15_test/, results/h15_scale/,
results/h15_analysis.md.
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))   # the qi_* modules
import json, os, sys
import numpy as np
import pandas as pd
from scipy import stats
from qi_experiment import (spec, make_jobs, run_experiment, load_experiment, paired_table, mean_ranks, holm,
                           TUNE_FAMILIES, TUNE_INST_SEEDS, TEST_FAMILIES, family_name)

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.environ.get("QI_RESULTS_DIR", os.path.join(os.path.dirname(HERE), "results"))
BUDGET, P, C = 20000, 30, 0.25
PX_GRID = [0.1, 0.25, 0.5, 1.0]
PHASES = ["greedy", "all"]
H15_INST_SEEDS = list(range(801, 811))              # never used before (static: H5 101-110, H7 201-210, H14 701-710)
SEL_PATH = os.path.join(RES, "h15_selection.json")
SCALE_SIZES = [500, 1000, 1500, 2000, 5000]
SCALE_FAMILIES = [(n, 50, "uniform", "high") for n in SCALE_SIZES]


def cxm(px, phases):
    return spec("run_qidmo", decoherence_c=C, exchange=px, exchange_phases=phases)


def tune_algos():
    a = {"QI-DMO": spec("run_qidmo", decoherence_c=C)}
    for ph in PHASES:
        for px in PX_GRID:
            a[f"QI-DMO+CXM {ph} px={px}"] = cxm(px, ph)
    return a


def selected():
    sel = json.load(open(SEL_PATH))
    return sel["phases"], sel["px"]


def test_algos():
    ph, px = selected()
    return {"QI-DMO": spec("run_qidmo", decoherence_c=C), "QI-DMO+CXM selected": cxm(px, ph),
            "QI-DMO+CXM H14 (all, px=1)": cxm(1.0, "all")}


def stage_tune():
    jobs = make_jobs("h15_tune", tune_algos(), TUNE_FAMILIES, TUNE_INST_SEEDS, list(range(10)), BUDGET, P)
    df = run_experiment("h15_tune", jobs, config={"stage": "tune", "px_grid": PX_GRID, "phases": PHASES, "budget": BUDGET, "P": P,
                                                  "note": "development set = pilot instances; selection bias applies to any number reported from it"})
    cands = [f"QI-DMO+CXM {ph} px={px}" for ph in PHASES for px in PX_GRID]
    r = mean_ranks(df, cands, metric="gap2", block=("family", "inst_seed", "run_seed"))
    g2 = df.groupby("algo").gap2.mean()
    # pre-registered rule: best mean rank; ties -> lower mean gap2; then the smaller p_x
    order = sorted(cands, key=lambda a: (round(r[a], 9), round(g2[a], 12), float(a.split("px=")[1])))
    best = order[0]
    sel = {"phases": best.split()[1], "px": float(best.split("px=")[1]), "selected": best,
           "mean_ranks": {a: round(float(r[a]), 4) for a in order}, "mean_gap2": {a: round(float(g2[a]), 6) for a in order},
           "reference_QI-DMO_mean_gap2": round(float(g2["QI-DMO"]), 6)}
    if os.path.exists(SEL_PATH):
        raise RuntimeError(f"{SEL_PATH} exists (write-once)")
    json.dump(sel, open(SEL_PATH, "w"), indent=1)
    print(json.dumps(sel, indent=1))


def stage_test():
    ph, px = selected()
    jobs = make_jobs("h15_test", test_algos(), TEST_FAMILIES, H15_INST_SEEDS, [0, 1], BUDGET, P)
    run_experiment("h15_test", jobs, config={"stage": "test", "phases": ph, "px": px, "budget": BUDGET, "P": P,
                                             "families": [family_name(f) for f in TEST_FAMILIES], "inst_seeds": H15_INST_SEEDS})


def stage_scale():
    ph, px = selected()
    jobs = make_jobs("h15_scale", {"QI-DMO+CXM selected": cxm(px, ph)}, SCALE_FAMILIES, [1], list(range(10)), BUDGET, P)
    run_experiment("h15_scale", jobs, config={"phases": ph, "px": px, "budget": BUDGET, "P": P, "sizes": SCALE_SIZES,
                                              "inst_seeds": [1], "run_seeds": list(range(10)), "compare_with": "results/scale_tasks QI-DMO"})


def analysis_text():
    sel = json.load(open(SEL_PATH))
    tune, test = load_experiment("h15_tune"), load_experiment("h15_test")
    algos = list(test_algos())
    out = ["# H15 analysis — the swap move only in QI-DMO's greedy phases\n",
           "Generated by `python experiments/exp_h15_qidmo_greedy_cxm.py analyze` from `results/h15_tune/`, `results/h15_test/` (fresh "
           "instance seeds 801-810, 2 run seeds, 20 000 evaluations, P = 30, c = 0.25) and `results/h15_scale/`. gap2 = gap to "
           "the preemptive lower bound, in %. Protocol: research_plan_v5.md §33.\n",
           f"## Development stage (selection bias applies)\n\nSelected: **{sel['selected']}** (phases = {sel['phases']}, "
           f"p_x = {sel['px']}).\n"]
    t = pd.DataFrame({"mean rank (40 blocks)": sel["mean_ranks"], "mean gap2 (%)": {a: 100 * v for a, v in sel["mean_gap2"].items()}})
    out.append(t.round(4).reset_index(names="configuration").to_markdown(index=False, floatfmt=".4f"))
    out.append(f"\nQI-DMO without the move on the development set: mean gap2 {100 * sel['reference_QI-DMO_mean_gap2']:.4f} %.\n")
    pv = tune.pivot_table(index="family", columns="algo", values="gap2", aggfunc="mean") * 100
    out.append(pv.round(3).reset_index().to_markdown(index=False, floatfmt=".3f"))

    out.append("\n## Held-out test: mean gap2 (%) per family\n")
    pv = test.pivot_table(index="family", columns="algo", values="gap2", aggfunc="mean")[algos] * 100
    out.append(pv.round(3).reset_index().to_markdown(index=False, floatfmt=".3f"))
    cols = ["family", "pairs", "mean A", "mean B", "diff A-B", "CI95 lo", "CI95 hi", "wins A", "ties", "wins B", "p", "p_holm", "r_rb", "A12"]
    out.append("\n## Paired comparisons (unit = instance, mean of 2 run seeds; diff in gap2 pp; Holm across 8 families; "
               "ALL = pooled over the 80 instances)\n")
    tables = {}
    for a, b, label in [("QI-DMO+CXM selected", "QI-DMO", "P1/P2 (primary): the selected configuration vs QI-DMO"),
                        ("QI-DMO+CXM H14 (all, px=1)", "QI-DMO", "replication of H14 on fresh instances (not part of P1/P2)"),
                        ("QI-DMO+CXM selected", "QI-DMO+CXM H14 (all, px=1)", "selected vs the H14 configuration")]:
        t = paired_table(test, a, b, metric="gap2"); tables[(a, b)] = t
        out.append(f"### {label}: A = {a}, B = {b}\n"); out.append(t[cols].to_markdown(index=False, floatfmt=".4f") + "\n")
    t = tables[("QI-DMO+CXM selected", "QI-DMO")]
    pooled, fams = t[t.family == "ALL"].iloc[0], t[t.family != "ALL"]
    p1 = bool(pooled["diff A-B"] < 0 and pooled["CI95 hi"] < 0 and pooled["p"] < 0.05)
    worse = fams[(fams["diff A-B"] > 0) & (fams["p_holm"] < 0.05)]
    p2 = len(worse) == 0
    out.append("## Pre-registered criteria (computed mechanically)\n")
    out.append(f"* **P1:** mean diff {pooled['diff A-B']:.4f} pp, CI95 [{pooled['CI95 lo']:.4f}, {pooled['CI95 hi']:.4f}], "
               f"Wilcoxon p = {pooled['p']:.3g}, the selected configuration better on {int(pooled['wins A'])} of "
               f"{int(pooled['pairs'])} instances -> **{'holds' if p1 else 'fails'}**.")
    out.append(f"* **P2:** families with a Holm-significant deterioration: {len(worse)} "
               f"({', '.join(worse.family) if len(worse) else 'none'}) -> **{'holds' if p2 else 'fails'}**.")
    verdict = "RETAIN" if (p1 and p2) else ("RETAIN WITH BOUNDARY" if p1 else "REJECT")
    out.append(f"* **Verdict by §33:** **{verdict}**.\n")
    mech = ["x_success", "x_frac", "end_impr_swap", "end_impr_reloc", "last_gb_impr_frac", "improving", "move_size", "purity_end", "runtime_s"]
    out.append("## Mechanism diagnostics (means over runs)\n")
    out.append(test.groupby("algo")[mech].mean().reindex(algos).round(4).reset_index().to_markdown(index=False, floatfmt=".4f"))

    sc = load_experiment("h15_scale")
    base = load_experiment("scale_tasks"); base = base[base.algo == "QI-DMO"]
    rows, ps = [], []
    for n in SCALE_SIZES:
        xa = sc[sc.n == n].makespan.values; xb = base[base.n == n].makespan.values
        p = stats.mannwhitneyu(xa, xb, alternative="two-sided").pvalue; ps.append(p)
        rows.append({"tasks": n, "QI-DMO mean (s)": xb.mean(), "selected mean (s)": xa.mean(), "selected sd (s)": xa.std(ddof=1),
                     "diff selected - QI-DMO (s)": xa.mean() - xb.mean(), "every selected run better": bool(xa.max() < xb.min()),
                     "p (Mann-Whitney)": p, "runtime QI-DMO (s)": base[base.n == n].runtime_s.mean(),
                     "runtime selected (s)": sc[sc.n == n].runtime_s.mean()})
    for r, ph in zip(rows, holm(ps)): r["p_holm"] = ph
    out.append("\n## P3 (descriptive): scaling problems, 50 VMs, 10 runs (QI-DMO from results/scale_tasks)\n")
    out.append(pd.DataFrame(rows).to_markdown(index=False, floatfmt=".4f"))
    return "\n".join(out) + "\n"


def stage_analyze():
    path = os.path.join(RES, "h15_analysis.md")
    if os.path.exists(path):
        raise RuntimeError(f"{path} exists (write-once)")
    txt = analysis_text(); open(path, "w").write(txt); print(txt)


if __name__ == "__main__":
    {"tune": stage_tune, "test": stage_test, "scale": stage_scale, "analyze": stage_analyze}[sys.argv[1]]()
